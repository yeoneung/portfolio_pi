"""Reproduce the fixed-policy certificate comparison without changing the policy."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "experiments"))
import policy_loss_certificate as p
import portfolio_welfare as w

CASES = ((16, 48, 4, "0.00005"), (32, 64, 6, "0.00002"))
TABLE = ROOT / "results/tables/tab_policy_loss.tex"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refit", action="store_true")
    args = parser.parse_args()
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text("% Fixed-policy verification incomplete.\n\\textit{No certificate returned.}\n")
    p.OUT.mkdir(exist_ok=True)
    summary_path = p.OUT / "comparison_results.json"
    summary_path.write_text('{"certified": false, "reason": "run incomplete"}\n')
    policy_hash = hashlib.sha256(p.POLICY_PATH.read_bytes()).hexdigest()
    old = json.loads((ROOT / "results/portfolio_welfare/welfare_results.json").read_text())
    if not old["certified"] or old["results"][0]["candidate_sha256"] != policy_hash:
        raise ValueError("Baseline certificate does not match the fixed policy")
    for key, file in (("verifier_sha256", "experiments/portfolio_welfare.py"),
                      ("arithmetic_core_sha256", "experiments/direct_residual_certificate.py")):
        if old[key] != hashlib.sha256((ROOT / file).read_bytes()).hexdigest():
            raise ValueError("Baseline verification sources changed")
    rows = []
    for dt, dx, rw, target in CASES:
        command = [sys.executable, "-B", "experiments/policy_loss_certificate.py",
                   "--degree-time", str(dt), "--degree-space", str(dx), "--reweights", str(rw)]
        if args.refit:
            subprocess.run(command, cwd=ROOT, check=True)
        subprocess.run(command+["--verify-only", "--target-residual", target], cwd=ROOT, check=True)
        stem = f"evaluation_{dt}_{dx}_{rw}"
        result = json.loads((p.OUT / (stem+"_certificate.json")).read_text())
        if not result["certified"] or result["policy_sha256"] != policy_hash or result["source_sha256"] != p.source_hashes():
            raise ArithmeticError("Incomplete or stale policy certificate")
        diagnostic = json.loads((p.OUT / (stem+"_diagnostics.json")).read_text())
        rows.append({"degree_time": dt, "degree_space": dx,
                     "fitting_seconds_recorded": diagnostic["fitting_seconds"], **result})
    if hashlib.sha256(p.POLICY_PATH.read_bytes()).hexdigest() != policy_hash:
        raise ArithmeticError("Comparison changed the policy")
    baseline = old["results"][0]
    reduction = w.lower(w.mpiv(baseline["bounds"]["relative_ce_loss_bp_upper"])/
                        w.mpiv(rows[-1]["bounds"]["relative_ce_loss_bp_upper"]))
    summary = {"certified": True, "policy_updates": 0, "policy_sha256": policy_hash,
               "baseline": baseline, "reevaluations": rows, "bound_reduction_factor_lower": reduction,
               "timing_scope": "recorded wall clock; supplied fits may have been run concurrently; no speed claim"}
    summary_path.write_text(json.dumps(summary, indent=2)+"\n")
    line = ["% Generated by analysis/reproduce_policy_loss.py; bounds rounded upward.",
            r"\begin{tabular}{lrrrr}\toprule",
            r"Evaluation & Residual & Gap bound & CE loss (bp) & Verify (s)\\\midrule",
            "Generating $u$ & $"+w.exact.upper_sci(baseline["certificate"]["residual_sup_upper"])+"$ & --- & $"+
            w.exact.upper_sci(baseline["bounds"]["relative_ce_loss_bp_upper"])+r"$ & ---\\"]
    for row in rows:
        cert, bounds = row["certificate"], row["bounds"]
        line.append(f"$({row['degree_time']},{row['degree_space']})$ & $"+
                    w.exact.upper_sci(cert["frozen_residual_upper"])+"$ & $"+
                    w.exact.upper_sci(cert["hamiltonian_gap_upper"])+"$ & $"+
                    w.exact.upper_sci(bounds["relative_ce_loss_bp_upper"])+f"$ & {row['verification_seconds']:.1f}"+r"\\")
    line.append(r"\bottomrule\end{tabular}")
    TABLE.write_text("\n".join(line)+"\n")
    print(json.dumps({"certified": True, "bound_reduction_factor_lower": reduction,
                      "uniform_inner_bounds": rows[-1]["uniform_inner_bounds"]}, indent=2), flush=True)


if __name__ == "__main__":
    main()
